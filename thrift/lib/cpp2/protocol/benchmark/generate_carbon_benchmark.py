@dataclasses.dataclass(frozen=True)
class Field:
    field_id: int
    cpp_type: str
    name: str


@dataclasses.dataclass(frozen=True)
class Struct:
    name: str
    fields: tuple[Field, ...]


@dataclasses.dataclass(frozen=True)
class Program:
    namespace: str
    thrift_namespace: str
    structs: tuple[Struct, ...]


def split_template_arguments(value: str) -> list[str]:
    parts: list[str] = []
    depth = 0
    begin = 0
    for index, char in enumerate(value):
        if char == "<":
            depth += 1
        elif char == ">":
            depth -= 1
        elif char == "," and depth == 0:
            parts.append(value[begin:index].strip())
            begin = index + 1
    if depth != 0:
        raise ValueError(f"unbalanced template type: {value}")
    parts.append(value[begin:].strip())
    return parts


def parse_template(cpp_type: str, template_name: str) -> list[str] | None:
    prefix = f"{template_name}<"
    if not cpp_type.startswith(prefix) or not cpp_type.endswith(">"):
        return None
    return split_template_arguments(cpp_type[len(prefix) : -1])


def parse_program(text: str) -> Program:
    text = re.sub(r"/\*.*?\*/", "", text, flags=re.DOTALL)
    text = re.sub(r"//[^\n]*", "", text)
    namespace_match = re.search(r"\bnamespace\s+([A-Za-z_]\w*)\s*;", text)
    thrift_namespace_match = re.search(
        r"\bthrift_namespace\s+([A-Za-z_]\w*(?:\.[A-Za-z_]\w*)*)\s*;",
        text,
    )
    if namespace_match is None or thrift_namespace_match is None:
        raise ValueError("both namespace and thrift_namespace are required")

    structs: list[Struct] = []
    for match in re.finditer(r"\bstruct\s+([A-Za-z_]\w*)\s*\{(.*?)\}\s*;", text, re.DOTALL):
        fields: list[Field] = []
        for declaration in match.group(2).split(";"):
            declaration = declaration.strip()
            if not declaration:
                continue
            field_match = re.fullmatch(
                r"([1-9]\d*)\s*:\s*(.+)\s+([A-Za-z_]\w*)", declaration
            )
            if field_match is None:
                raise ValueError(f"unsupported field declaration: {declaration!r}")
            fields.append(
                Field(
                    int(field_match.group(1)),
                    field_match.group(2).strip(),
                    field_match.group(3),
                )
            )
        if not fields:
            raise ValueError(f"struct {match.group(1)} must not be empty")
        if len({field.field_id for field in fields}) != len(fields):
            raise ValueError(f"duplicate field id in struct {match.group(1)}")
        structs.append(Struct(match.group(1), tuple(fields)))
    if not structs:
        raise ValueError("at least one struct is required")

    return Program(
        namespace_match.group(1),
        thrift_namespace_match.group(1),
        tuple(structs),
    )


SCALAR_THRIFT_TYPES = {
    "bool": "bool",
    "int8_t": "byte",
    "int16_t": "i16",
    "int32_t": "i32",
    "int64_t": "i64",
    "float": "float",
    "double": "double",
    "std::string": "string",
}


def thrift_type(cpp_type: str, map_aliases: dict[str, str]) -> str:
    if cpp_type in SCALAR_THRIFT_TYPES:
        return SCALAR_THRIFT_TYPES[cpp_type]
    vector_arguments = parse_template(cpp_type, "std::vector")
    if vector_arguments is not None:
        if len(vector_arguments) != 1:
            raise ValueError(f"std::vector requires one argument: {cpp_type}")
        return f"list<{thrift_type(vector_arguments[0], map_aliases)}>"
    map_arguments = parse_template(cpp_type, "std::map")
    if map_arguments is not None:
        if len(map_arguments) != 2:
            raise ValueError(f"std::map requires two arguments: {cpp_type}")
        key_type = thrift_type(map_arguments[0], map_aliases)
        value_type = thrift_type(map_arguments[1], map_aliases)
        alias = f"{key_type}_to_{value_type}_std_map".replace("<", "_").replace(
            ">", "_"
        )
        alias = re.sub(r"[^A-Za-z0-9_]", "_", alias)
        map_aliases.setdefault(cpp_type, alias)
        return alias
    raise ValueError(f"unsupported Carbon benchmark field type: {cpp_type}")


def qualified_namespace(namespace: str) -> str:
    return namespace.replace(".", "::")


def render_thrift(program: Program) -> str:
    map_aliases: dict[str, str] = {}
    field_types: dict[tuple[str, str], str] = {}
    for struct in program.structs:
        for field in struct.fields:
            field_types[(struct.name, field.name)] = thrift_type(
                field.cpp_type, map_aliases
            )

    lines = [
        LICENSE,
        'include "thrift/annotation/cpp.thrift"',
        "",
        'package "apache.org/thrift/benchmark"',
        "",
        'cpp_include "<mcrouter/lib/carbon/CarbonProtocolReader.h>"',
        "",
        f"namespace cpp2 {program.thrift_namespace}",
        f"namespace py3 {program.thrift_namespace}",
        "",
    ]
    for cpp_type, alias in map_aliases.items():
        arguments = parse_template(cpp_type, "std::map")
        assert arguments is not None
        key_type = thrift_type(arguments[0], map_aliases)
        value_type = thrift_type(arguments[1], map_aliases)
        lines.extend(
            [
                f'@cpp.Type{{name = "{cpp_type}"}}',
                f"typedef map<{key_type}, {value_type}> {alias}",
                "",
            ]
        )
    for struct in program.structs:
        lines.append(f"struct {struct.name} {{")
        for field in struct.fields:
            lines.extend(
                [
                    "  @cpp.DeprecatedTerseWrite",
                    f"  {field.field_id}: {field_types[(struct.name, field.name)]} {field.name};",
                ]
            )
        lines.extend(["}", ""])
    return "\n".join(lines).rstrip() + "\n"


def render_declarations(program: Program, include_prefix: str) -> str:
    cpp_namespace = qualified_namespace(program.thrift_namespace)
    lines = [
        LICENSE,
        "#pragma once",
        "",
        "#include <type_traits>",
        "",
        "#include <mcrouter/lib/carbon/CarbonProtocolReader.h>",
        f'#include "{include_prefix}/gen-cpp2/CarbonTestData_types.h"',
        "",
        f"namespace {program.namespace} {{",
    ]
    for struct in program.structs:
        lines.append(f"using {struct.name} = {cpp_namespace}::{struct.name};")
    lines.extend(["}", "", "namespace carbon {"])
    for struct in program.structs:
        lines.extend(
            [
                "template <>",
                f"struct IsCarbonStruct<::{program.namespace}::{struct.name}> "
                ": std::true_type {};",
            ]
        )
    lines.extend(["}", "", f"namespace {cpp_namespace} {{"])
    for struct in program.structs:
        lines.extend(
            [
                "template <class Writer>",
                f"void serialize(const {struct.name}& self, Writer&& writer);",
                f"void deserialize({struct.name}& self, carbon::CarbonProtocolReader& reader);",
                "template <class Visitor>",
                f"void visitFields({struct.name}& self, Visitor&& visitor);",
                "template <class Visitor>",
                f"void visitFields(const {struct.name}& self, Visitor&& visitor);",
                "",
            ]
        )
    lines.extend(["}", ""])
    return "\n".join(lines)


def render_inline(program: Program, include_prefix: str) -> str:
    cpp_namespace = qualified_namespace(program.thrift_namespace)
    lines = [
        LICENSE,
        "#pragma once",
        "",
        f'#include "{include_prefix}/CarbonTestDataMessages-decl.h"',
        "",
        f"namespace {cpp_namespace} {{",
    ]
    for struct in program.structs:
        lines.extend(
            [
                "template <class Writer>",
                f"void serialize(const {struct.name}& self, Writer&& writer) {{",
                "  writer.writeStructBegin();",
            ]
        )
        for field in struct.fields:
            lines.append(
                f"  writer.writeField({field.field_id}, self.{field.name}_ref());"
            )
        lines.extend(
            ["  writer.writeFieldStop();", "  writer.writeStructEnd();", "}", ""]
        )
        for qualifier in ("", "const "):
            lines.extend(
                [
                    "template <class Visitor>",
                    f"void visitFields({qualifier}{struct.name}& self, Visitor&& visitor) {{",
                ]
            )
            for field in struct.fields:
                lines.extend(
                    [
                        f'  if (!visitor.visitField({field.field_id}, "{field.name}", *self.{field.name}_ref())) {{',
                        "    return;",
                        "  }",
                    ]
                )
            lines.extend(["}", ""])
    lines.extend(["}", ""])
    return "\n".join(lines)


def render_deserialization(program: Program, include_prefix: str) -> str:
    cpp_namespace = qualified_namespace(program.thrift_namespace)
    lines = [
        LICENSE,
        f'#include "{include_prefix}/CarbonTestDataMessages.h"',
        "",
        f"namespace {cpp_namespace} {{",
    ]
    for struct in program.structs:
        lines.extend(
            [
                f"void deserialize({struct.name}& self, carbon::CarbonProtocolReader& reader) {{",
                "  reader.readStructBegin();",
                "  while (true) {",
                "    const auto [fieldType, fieldId] = reader.readFieldHeader();",
                "    if (fieldType == carbon::FieldType::Stop) {",
                "      break;",
                "    }",
                "    switch (fieldId) {",
            ]
        )
        for field in struct.fields:
            lines.extend(
                [
                    f"      case {field.field_id}:",
                    f"        reader.readField(self.{field.name}_ref(), fieldType);",
                    "        break;",
                ]
            )
        lines.extend(
            [
                "      default:",
                "        reader.skip(fieldType);",
                "        break;",
                "    }",
                "  }",
                "  reader.readStructEnd();",
                "}",
                "",
            ]
        )
    lines.extend(["}", ""])
    return "\n".join(lines)


def render_include_file(include_prefix: str, header: str) -> str:
    return f'{LICENSE}\n#pragma once\n\n#include "{include_prefix}/{header}"\n'


def write_output(path: pathlib.Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--input", required=True, type=pathlib.Path)
    parser.add_argument("--output-dir", required=True, type=pathlib.Path)
    parser.add_argument("--include-prefix", required=True)
    # Accepted as part of the common Carbon provider contract. This strict
    # benchmark subset has no imports, so it does not otherwise use the root.
    parser.add_argument("--source-root", type=pathlib.Path)
    arguments = parser.parse_args()

    try:
        program = parse_program(arguments.input.read_text(encoding="utf-8"))
        output_dir = arguments.output_dir
        prefix = arguments.include_prefix.rstrip("/")
        write_output(output_dir / "CarbonTestData.thrift", render_thrift(program))
        write_output(
            output_dir / "CarbonTestDataMessages-decl.h",
            render_declarations(program, prefix),
        )
        write_output(
            output_dir / "CarbonTestDataMessages-inl.h",
            render_inline(program, prefix),
        )
        write_output(
            output_dir / "CarbonTestDataMessagesThrift.cpp",
            render_deserialization(program, prefix),
        )
        write_output(
            output_dir / "CarbonTestDataMessages.h",
            render_include_file(prefix, "CarbonTestDataMessages-decl.h")
            + f'\n#include "{prefix}/CarbonTestDataMessages-inl.h"\n',
        )
        write_output(
            output_dir / "CarbonTestData.h",
            render_include_file(prefix, "CarbonTestDataMessages.h"),
        )
        write_output(
            output_dir / "CarbonTestDataMessages.cpp",
            f'{LICENSE}\n#include "{prefix}/CarbonTestDataMessages.h"\n',
        )
    except (OSError, ValueError) as error:
        print(f"carbon benchmark codegen: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
